#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

import {
  CAFE_MEDIA_SOURCES,
  CAFE_MEDIA_VERSION,
  MAP_MEDIA_SOURCES,
  cafeMediaObjectPath,
  mapMediaObjectPath,
} from "./cafe-media-config.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const publicRoot = path.join(root, "public");
const generatedMediaRoot = path.join(publicRoot, "media");
const manifestJsonFile = path.join(generatedMediaRoot, `manifest-${CAFE_MEDIA_VERSION}.json`);
const manifestModuleFile = path.join(root, "src", "ai-native", "media", "mediaManifest.generated.js");

const SPECS = Object.freeze({
  thumbnail: { width: 320, height: 228, quality: 66, alphaQuality: 78, maxBytes: 55_000 },
  scene: { width: 760, height: 540, quality: 72, alphaQuality: 84, maxBytes: 180_000 },
  map: { width: 1536, height: 1024, quality: 76, maxBytes: 600_000 },
});

function digest(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

async function writeDerivedAsset(buffer, objectPath, spec, { requireAlpha = false } = {}) {
  if (buffer.length > spec.maxBytes) {
    throw new Error(`${objectPath} exceeds ${spec.maxBytes} bytes: ${buffer.length}`);
  }
  const metadata = await sharp(buffer).metadata();
  if (metadata.format !== "webp") throw new Error(`${objectPath} is not WebP`);
  if (metadata.width > spec.width || metadata.height > spec.height) {
    throw new Error(`${objectPath} exceeds ${spec.width}x${spec.height}`);
  }
  if (requireAlpha && !metadata.hasAlpha) throw new Error(`${objectPath} lost its alpha channel`);
  const output = path.join(publicRoot, objectPath);
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, buffer);
  return {
    role: objectPath.includes("thumbnail-") ? "thumbnail" : objectPath.includes("scene-") ? "scene" : "board",
    path: objectPath,
    width: metadata.width,
    height: metadata.height,
    bytes: buffer.length,
    mime_type: "image/webp",
    content_hash: digest(buffer),
    version: CAFE_MEDIA_VERSION,
  };
}

await rm(generatedMediaRoot, { recursive: true, force: true });
await mkdir(path.dirname(manifestModuleFile), { recursive: true });

const cafes = {};
for (const sourceConfig of CAFE_MEDIA_SOURCES) {
  const source = path.join(publicRoot, "assets", "cafes", sourceConfig.source);
  await readFile(source);

  const variants = {};
  for (const role of ["thumbnail", "scene"]) {
    const spec = SPECS[role];
    const buffer = await sharp(source)
      .resize({ width: spec.width, height: spec.height, fit: "inside", withoutEnlargement: true, kernel: "lanczos3" })
      .webp({ quality: spec.quality, alphaQuality: spec.alphaQuality, effort: 6, smartSubsample: true })
      .toBuffer();
    const contentHash = digest(buffer);
    const objectPath = cafeMediaObjectPath(sourceConfig.cafeId, role, contentHash);
    variants[role] = await writeDerivedAsset(buffer, objectPath, spec, { requireAlpha: true });
  }

  cafes[sourceConfig.cafeId] = {
    cafe_id: sourceConfig.cafeId,
    key: sourceConfig.key,
    legacy_paths: [sourceConfig.legacyPath, `public${sourceConfig.legacyPath}`],
    ...variants,
  };
}

const maps = {};
for (const sourceConfig of MAP_MEDIA_SOURCES) {
  const spec = SPECS.map;
  const source = path.join(publicRoot, "assets", "map", sourceConfig.source);
  const buffer = await sharp(source)
    .resize({ width: spec.width, height: spec.height, fit: "inside", withoutEnlargement: true, kernel: "lanczos3" })
    .webp({ quality: spec.quality, effort: 6, smartSubsample: true })
    .toBuffer();
  const contentHash = digest(buffer);
  const objectPath = mapMediaObjectPath(sourceConfig.regionId, contentHash);
  maps[sourceConfig.regionId] = {
    region_id: sourceConfig.regionId,
    board: await writeDerivedAsset(buffer, objectPath, spec),
  };
}

const manifest = {
  schema_version: "1.0.0",
  media_version: CAFE_MEDIA_VERSION,
  generated_from: "QuietLens controlled watercolor masters",
  cafes,
  maps,
};
const serializedManifest = `${JSON.stringify(manifest, null, 2)}\n`;
await writeFile(manifestJsonFile, serializedManifest);
const manifestHash = digest(Buffer.from(serializedManifest));

const moduleSource = `// Generated by scripts/generate-cafe-media.mjs. Do not edit manually.\n`
  + `export const MEDIA_MANIFEST_HASH = ${JSON.stringify(manifestHash)};\n`
  + `export const MEDIA_MANIFEST = Object.freeze(${JSON.stringify(manifest, null, 2)});\n`;
await writeFile(manifestModuleFile, moduleSource);

const cafeBytes = Object.values(cafes).reduce((sum, item) => sum + item.thumbnail.bytes + item.scene.bytes, 0);
const mapBytes = Object.values(maps).reduce((sum, item) => sum + item.board.bytes, 0);
console.log(`Generated ${Object.keys(cafes).length} cafe media pairs and ${Object.keys(maps).length} map boards (${cafeBytes + mapBytes} bytes, manifest ${manifestHash.slice(0, 12)})`);
